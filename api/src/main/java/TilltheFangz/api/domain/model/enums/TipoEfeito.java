package TilltheFangz.api.domain.model.enums;

/**
 * Define o atributo ou recurso que será alterado pelo efeito de um item.
 *
 * Os valores positivos representam um aumento e os valores negativos
 * representam uma redução no atributo ou recurso afetado.
 */

public enum TipoEfeito {
    DANO,
    VIDA,
    INTELIGENCIA,
    CARISMA,
    FORCA,
    SORTE,
    AGILIDADE,
    SANIDADE,
    DEFESA,
    SANGUE_ANCESTRAL
}
